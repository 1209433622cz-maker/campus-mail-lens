export function translate(language, key, values = {}) {
  const wording = copy[key]?.[language === "en" ? 1 : 0] ?? key
  return wording.replace(/\{(\w+)\}/g, (token, name) => values[name] ?? token)
}

export function copyForAudience(language, audience) {
  const all = audience.label.includes("全校师生")
  const allStudents = audience.roles.length === 2 && audience.roles.includes("graduate") && audience.roles.includes("undergraduate")
  const description = all ? translate(language, "audience.allPeople")
    : allStudents ? translate(language, "audience.allStudents")
      : audience.roles.map(role => translate(language, "profile." + role)).join(language === "en" ? ", " : "、")
  const school = language === "en" ? englishSchools[audience.unit] ?? audience.unit : audience.unit
  return [school, description].filter(Boolean).join(" · ") || translate(language, "audience.unspecified")
}

export function setPageLanguage(language) {
  const english = language === "en"
  document.documentElement.lang = english ? "en" : "zh-Hans"
  document.title = translate(language, "pageTitle")
  document.querySelector('meta[name="description"]').content = translate(language, "pageDescription")
  for (const [data, attribute] of [["copy", null], ["copyLabel", "aria-label"], ["copyPlaceholder", "placeholder"], ["copyAlt", "alt"]]) {
    const selector = "[data-" + data.replace(/[A-Z]/g, letter => "-" + letter.toLowerCase()) + "]"
    for (const node of document.querySelectorAll(selector)) {
      const value = translate(language, node.dataset[data])
      if (attribute) node.setAttribute(attribute, value)
      else node.textContent = value
    }
  }
  const toggle = document.getElementById("language-toggle")
  toggle.textContent = english ? "中文" : "EN"
  toggle.lang = english ? "zh-Hans" : "en"
  toggle.title = translate(language, "switchLanguage")
  for (const link of document.querySelectorAll("[data-english-url]")) {
    link.href = english ? link.dataset.englishUrl : link.dataset.chineseUrl
  }
}
